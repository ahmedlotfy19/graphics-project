static const unsigned char* getGlyph(char ch)
{
    if (ch >= 'a' && ch <= 'z') ch = ch - 'a' + 'A';
    if (ch < 32 || ch > 126) ch = '?';
    return font[ch - 32];
}

namespace Text
{
    void draw(Renderer2D& r, const std::string& text, float x, float y, float size, Color color, Align align)
    {
        float pixel = size / 7.0f;

        std::vector<std::string> lines(1);
        for (char ch : text)
        {
            if (ch == '\n') lines.push_back("");
            else            lines.back() += ch;
        }

        float lineY = y;
        for (const std::string& line : lines)
        {
            float width = line.size() * 6 * pixel - pixel;
            float penX = x;
            if (align == Align::Center) penX = x - width / 2;
            if (align == Align::Right)  penX = x - width;

            for (char ch : line)
            {
                const unsigned char* glyph = getGlyph(ch);
                for (int row = 0; row < 7; row++)
                    for (int col = 0; col < 5; col++)
                        if (glyph[row] & (0x10 >> col))
                            r.rect(penX + col * pixel, lineY + (6 - row) * pixel, pixel, pixel, color);
                penX += 6 * pixel;
            }

            lineY -= 10 * pixel;
        }
    }

    void drawShadowed(Renderer2D& r, const std::string& text, float x, float y, float size, Color color, Align align)
    {
        float offset = size / 12.0f;
        if (offset < 1) offset = 1;
        draw(r, text, x + offset, y - offset, size, Color(0, 0, 0, 0.7f), align);
        draw(r, text, x, y, size, color, align);
    }
}
